-- DB 설계 v1.5 6절: 날짜별 순회·조원·장소·촬영 구도·이벤트·시각 정정
-- 상태 전이(첫 개인 시작, 담당자 복귀 확인, 늦은 사진 보완)는 서비스가 잠금 아래 검사한다. 여기서는 상태와 함께 채워져야 하는 값만 강제한다.

CREATE TABLE patrols (
    id                         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    program_id                 uuid         NOT NULL REFERENCES programs (id),
    team_id                    uuid         NOT NULL,
    route_version_id           uuid         NOT NULL,
    organization_id            uuid         NOT NULL,
    base_organization_id       uuid         NOT NULL,
    activity_date              date         NOT NULL,
    scheduled_start_at         timestamptz  NOT NULL,
    expected_return_at         timestamptz  NOT NULL,
    team_name_snapshot         varchar(50)  NOT NULL,
    route_name_snapshot        varchar(100) NOT NULL,
    base_name_snapshot         varchar(100) NOT NULL,
    activity_status            varchar(20)  NOT NULL DEFAULT 'ASSIGNED'
        CHECK (activity_status IN ('ASSIGNED', 'IN_PROGRESS', 'RETURNING', 'COMPLETED', 'ABORTED', 'CANCELLED')),
    return_reason              varchar(10)  CHECK (return_reason IN ('NORMAL', 'ABORT')),
    abort_reason               varchar(10)  CHECK (abort_reason IN ('HEALTH', 'DEVICE', 'OTHER')),
    return_reason_source       varchar(10)  CHECK (return_reason_source IN ('REQUESTED', 'CONFIRMED')),
    return_reason_confirmed_at timestamptz,
    return_reason_confirmed_by uuid REFERENCES users (id),
    departed_at                timestamptz,
    departure_confirmed_at     timestamptz,
    departure_confirmed_by     uuid REFERENCES users (id),
    paused                     boolean      NOT NULL DEFAULT false,
    cancelled_at               timestamptz,
    cancelled_by               uuid REFERENCES users (id),
    cancellation_reason        varchar(500),
    finished_at                timestamptz,
    sync_deadline_at           timestamptz  NOT NULL,
    revision                   bigint       NOT NULL DEFAULT 0 CHECK (revision >= 0),
    version                    bigint       NOT NULL DEFAULT 0,
    created_at                 timestamptz  NOT NULL DEFAULT now(),
    updated_at                 timestamptz  NOT NULL DEFAULT now(),
    UNIQUE (program_id, id),
    FOREIGN KEY (program_id, team_id) REFERENCES teams (program_id, id),
    FOREIGN KEY (program_id, route_version_id) REFERENCES route_versions (program_id, id),
    FOREIGN KEY (program_id, organization_id) REFERENCES organizations (program_id, id),
    FOREIGN KEY (program_id, base_organization_id) REFERENCES organizations (program_id, id),
    CHECK (expected_return_at > scheduled_start_at),
    -- 사진 접수 기한: 활동일 다음 날 00:00 Asia/Seoul(D-17). 예정·복귀 시각 변경으로 늘리지 않는다.
    CHECK (sync_deadline_at = ((activity_date + 1)::timestamp AT TIME ZONE 'Asia/Seoul')),
    CHECK ((departure_confirmed_at IS NULL) = (departure_confirmed_by IS NULL)),
    CHECK ((activity_status = 'CANCELLED') = (cancelled_at IS NOT NULL)),
    CHECK ((cancelled_at IS NULL) = (cancelled_by IS NULL) AND (cancelled_at IS NULL) = (cancellation_reason IS NULL)),
    CHECK (cancellation_reason IS NULL OR length(btrim(cancellation_reason)) BETWEEN 1 AND 500),
    CHECK ((activity_status IN ('COMPLETED', 'ABORTED')) = (finished_at IS NOT NULL)),
    CHECK (abort_reason IS NULL OR return_reason = 'ABORT'),
    CHECK (return_reason IS NULL OR activity_status IN ('IN_PROGRESS', 'RETURNING', 'COMPLETED', 'ABORTED')),
    CHECK ((return_reason IS NULL) = (return_reason_source IS NULL)),
    CHECK ((return_reason_source = 'CONFIRMED') = (return_reason_confirmed_at IS NOT NULL)),
    CHECK ((return_reason_confirmed_at IS NULL) = (return_reason_confirmed_by IS NULL)),
    CHECK (return_reason_source IS DISTINCT FROM 'CONFIRMED' OR return_reason <> 'ABORT' OR abort_reason IS NOT NULL),
    CHECK (activity_status NOT IN ('COMPLETED') OR return_reason = 'NORMAL'),
    CHECK (activity_status NOT IN ('ABORTED') OR return_reason = 'ABORT')
);
CREATE INDEX ix_patrols_today ON patrols (program_id, activity_date, organization_id, activity_status);

CREATE TABLE patrol_members (
    id                             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    program_id                     uuid        NOT NULL REFERENCES programs (id),
    patrol_id                      uuid        NOT NULL,
    participant_id                 uuid        NOT NULL,
    user_id_snapshot               uuid        NOT NULL REFERENCES users (id),
    name_snapshot                  varchar(50) NOT NULL,
    seat_no                        smallint    NOT NULL CHECK (seat_no IN (1, 2, 3)),
    -- 같은 참여자의 시간 겹침 배정을 DB가 막도록 순회 일정을 복제한다. 순회 일정 변경 시 같은 트랜잭션에서 갱신한다.
    activity_date                  date        NOT NULL,
    scheduled_range                tstzrange   NOT NULL,
    assignment_active              boolean     NOT NULL DEFAULT true,
    attendance                     varchar(10) NOT NULL DEFAULT 'UNCHECKED' CHECK (attendance IN ('UNCHECKED', 'PRESENT', 'ABSENT')),
    attendance_requested_at        timestamptz,
    attendance_request_received_at timestamptz,
    attendance_checked_by          uuid REFERENCES users (id),
    attendance_checked_at          timestamptz,
    proxy_attendance_reason        varchar(500),
    started_at                     timestamptz,
    start_received_at              timestamptz,
    start_source                   varchar(20) CHECK (start_source IN ('SELF', 'ADMIN_CORRECTION')),
    returned_at                    timestamptz,
    return_source                  varchar(30) CHECK (return_source IN ('MANAGER_CONFIRMATION', 'ADMIN_CORRECTION')),
    return_confirmed_at            timestamptz,
    return_confirmed_by            uuid REFERENCES users (id),
    version                        bigint      NOT NULL DEFAULT 0,
    created_at                     timestamptz NOT NULL DEFAULT now(),
    updated_at                     timestamptz NOT NULL DEFAULT now(),
    UNIQUE (program_id, id),
    UNIQUE (patrol_id, participant_id),
    UNIQUE (patrol_id, user_id_snapshot),
    FOREIGN KEY (program_id, patrol_id) REFERENCES patrols (program_id, id),
    FOREIGN KEY (program_id, participant_id) REFERENCES participants (program_id, id),
    CHECK (NOT isempty(scheduled_range)),
    CHECK ((attendance_requested_at IS NULL) = (attendance_request_received_at IS NULL)),
    CHECK ((attendance_checked_at IS NULL) = (attendance_checked_by IS NULL)),
    CHECK ((attendance = 'UNCHECKED') = (attendance_checked_at IS NULL)),
    CHECK (proxy_attendance_reason IS NULL OR length(btrim(proxy_attendance_reason)) BETWEEN 1 AND 500),
    CHECK ((started_at IS NULL) = (start_source IS NULL)),
    CHECK (start_received_at IS NULL OR started_at IS NOT NULL),
    CHECK ((returned_at IS NULL) = (return_source IS NULL)),
    CHECK (started_at IS NULL OR returned_at IS NULL OR started_at <= returned_at),
    CHECK ((return_confirmed_at IS NULL) = (return_confirmed_by IS NULL)),
    CHECK (return_confirmed_at IS NULL OR returned_at IS NOT NULL),
    -- 배정 중인 같은 참여자의 시간 겹침 금지(D-05, ACT-04)
    EXCLUDE USING gist (participant_id WITH =, scheduled_range WITH &&) WHERE (assignment_active)
);
CREATE UNIQUE INDEX ux_patrol_members_active_seat ON patrol_members (patrol_id, seat_no) WHERE assignment_active;
CREATE INDEX ix_patrol_members_participant ON patrol_members (participant_id, patrol_id);

CREATE TABLE patrol_stops (
    id                       uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    program_id               uuid          NOT NULL REFERENCES programs (id),
    patrol_id                uuid          NOT NULL,
    source_route_stop_id     uuid,
    facility_id              uuid          NOT NULL,
    sequence_no              integer       NOT NULL CHECK (sequence_no >= 1),
    name_snapshot            varchar(100)  NOT NULL,
    type_snapshot            varchar(30)   NOT NULL CHECK (type_snapshot IN ('SIDEWALK', 'DRAIN', 'BENCH', 'SAFETY_FENCE', 'EXERCISE_EQUIPMENT',
                                                                             'PARK_EQUIPMENT', 'SNOW_REMOVAL_BIN', 'SHADE_STRUCTURE')),
    latitude_snapshot        numeric(9, 6),
    longitude_snapshot       numeric(10, 6),
    instruction_snapshot     varchar(500),
    department_snapshot_id   uuid          NOT NULL,
    visit_status             varchar(20)   NOT NULL DEFAULT 'PENDING'
        CHECK (visit_status IN ('PENDING', 'CAPTURED', 'SKIPPED', 'REVIEW_REQUESTED', 'NOT_VISITED')),
    -- 중도 복귀로 자동 미방문이 된 장소만 늦은 적법 사진으로 보완할 수 있다(D-27).
    not_visited_reason       varchar(20)   CHECK (not_visited_reason IN ('AUTO_ABORT')),
    UNIQUE (program_id, id),
    UNIQUE (patrol_id, sequence_no),
    UNIQUE (id, patrol_id),
    UNIQUE (id, facility_id),
    FOREIGN KEY (program_id, patrol_id) REFERENCES patrols (program_id, id),
    FOREIGN KEY (program_id, source_route_stop_id) REFERENCES route_stops (program_id, id),
    FOREIGN KEY (program_id, facility_id) REFERENCES facilities (program_id, id),
    FOREIGN KEY (program_id, department_snapshot_id) REFERENCES organizations (program_id, id),
    CHECK (not_visited_reason IS NULL OR visit_status = 'NOT_VISITED'),
    CHECK ((latitude_snapshot IS NULL) = (longitude_snapshot IS NULL))
);

CREATE TABLE capture_slots (
    id                    uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    program_id            uuid         NOT NULL REFERENCES programs (id),
    patrol_stop_id        uuid         NOT NULL,
    source_template_id    uuid,
    sequence_no           integer      NOT NULL CHECK (sequence_no >= 1),
    label                 varchar(50)  NOT NULL,
    instruction           varchar(500),
    reference_media_id    uuid,
    required              boolean      NOT NULL DEFAULT true,
    purpose               varchar(20)  NOT NULL DEFAULT 'REGULAR' CHECK (purpose IN ('REGULAR', 'REINSPECTION')),
    accepted_inspection_id uuid,
    active_inspection_id  uuid,
    quality_failure_count smallint     NOT NULL DEFAULT 0 CHECK (quality_failure_count BETWEEN 0 AND 3),
    resolution            varchar(20)  NOT NULL DEFAULT 'OPEN' CHECK (resolution IN ('OPEN', 'ACCEPTED', 'REVIEW_REQUESTED', 'SKIPPED')),
    version               bigint       NOT NULL DEFAULT 0,
    created_at            timestamptz  NOT NULL DEFAULT now(),
    updated_at            timestamptz  NOT NULL DEFAULT now(),
    UNIQUE (program_id, id),
    UNIQUE (patrol_stop_id, sequence_no),
    FOREIGN KEY (program_id, patrol_stop_id) REFERENCES patrol_stops (program_id, id),
    FOREIGN KEY (program_id, source_template_id) REFERENCES route_capture_templates (program_id, id),
    FOREIGN KEY (program_id, reference_media_id) REFERENCES media (program_id, id),
    CHECK ((resolution = 'ACCEPTED') = (accepted_inspection_id IS NOT NULL)),
    CHECK (accepted_inspection_id IS NULL OR active_inspection_id IS NULL),
    CHECK (resolution = 'OPEN' OR active_inspection_id IS NULL)
);
-- accepted/active 포인터의 복합 FK는 inspections 생성 후 V4에서 추가한다.

CREATE TABLE patrol_events (
    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    program_id      uuid        NOT NULL REFERENCES programs (id),
    patrol_id       uuid        NOT NULL,
    patrol_stop_id  uuid,
    actor_user_id   uuid        NOT NULL REFERENCES users (id),
    client_event_id uuid,
    request_hash    bytea,
    type            varchar(30) NOT NULL CHECK (type IN ('ATTENDANCE_REQUESTED', 'ACTIVITY_STARTED', 'STOP_SKIPPED', 'PAUSE_STARTED',
                                                         'PAUSE_ENDED', 'RETURN_REQUESTED', 'FOLLOW_UP_RECORDED')),
    reason_code     varchar(30),
    occurred_at     timestamptz NOT NULL,
    received_at     timestamptz NOT NULL DEFAULT now(),
    payload_json    jsonb,
    FOREIGN KEY (program_id, patrol_id) REFERENCES patrols (program_id, id),
    FOREIGN KEY (patrol_stop_id, patrol_id) REFERENCES patrol_stops (id, patrol_id),
    -- 시니어 이벤트는 사용자별 clientEventId로 멱등 처리한다(업무 API 2절)
    UNIQUE (actor_user_id, client_event_id),
    CHECK ((client_event_id IS NULL) = (request_hash IS NULL)),
    CHECK (type <> 'STOP_SKIPPED' OR (patrol_stop_id IS NOT NULL AND reason_code IN ('UNSAFE', 'NOT_FOUND', 'FACILITY_REMOVED', 'OTHER')))
);
CREATE INDEX ix_patrol_events_patrol ON patrol_events (patrol_id, occurred_at);

CREATE TABLE patrol_time_corrections (
    id                  uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    program_id          uuid         NOT NULL REFERENCES programs (id),
    patrol_id           uuid         NOT NULL,
    participant_id      uuid         NOT NULL,
    before_started_at   timestamptz,
    after_started_at    timestamptz,
    before_returned_at  timestamptz,
    after_returned_at   timestamptz,
    reason              varchar(500) NOT NULL CHECK (length(btrim(reason)) BETWEEN 1 AND 500),
    actor_user_id       uuid         NOT NULL REFERENCES users (id),
    recorded_at         timestamptz  NOT NULL DEFAULT now(),
    FOREIGN KEY (program_id, patrol_id) REFERENCES patrols (program_id, id),
    FOREIGN KEY (patrol_id, participant_id) REFERENCES patrol_members (patrol_id, participant_id),
    CHECK (after_started_at IS NOT NULL OR after_returned_at IS NOT NULL)
);
CREATE INDEX ix_patrol_time_corrections_patrol ON patrol_time_corrections (patrol_id, participant_id);
